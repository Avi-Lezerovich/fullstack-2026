/* Writes ../sw.js after `vite build`, so both windows keep working with no internet.
   - Precache: both pages, every emitted asset (hashed names, never stale), the code
     snapshot and maps, the icon and the manifest.
   - Pages are network-first with a short timeout: online you get the latest build,
     offline the cached copy of that page.
   - data/*.json is matched ignoring the query (code.json is fetched with ?v=<commit>).
   - Fonts are cached on first load. Old lolsuit-guide-* caches (also the pre-React
     guide's) are deleted on activate. */
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const OUT = fileURLToPath(new URL("../..", import.meta.url));
const DIRS = ["assets", "data", "img"];
const ROOT_FILES = ["index.html", "exam.html", "manifest.webmanifest"];

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const p = join(dir, name);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}

const files = [
  ...ROOT_FILES.map((f) => join(OUT, f)),
  ...DIRS.flatMap((d) => walk(join(OUT, d))),
];
const hash = createHash("sha256");
for (const f of files) hash.update(relative(OUT, f)).update(readFileSync(f));
const VERSION = hash.digest("hex").slice(0, 12);
const PRECACHE = files.map((f) => relative(OUT, f).split("\\").join("/"));

const sw = `/* Generated by app/scripts/write-sw.mjs — do not edit. */
const VERSION = ${JSON.stringify(VERSION)};
const PRECACHE = ${JSON.stringify(PRECACHE, null, 0)};
const CACHE = "lolsuit-guide-" + VERSION;
const RUNTIME = "lolsuit-guide-runtime";
const PAGES = ["index.html", "exam.html"];
const NETWORK_TIMEOUT_MS = 3000;

self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)).then(() => self.skipWaiting()));
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys
        .filter((key) => key.startsWith("lolsuit-guide-") && key !== CACHE && key !== RUNTIME)
        .map((key) => caches.delete(key))))
      .then(() => self.clients.claim())
  );
});

function pageOf(url) {
  const name = new URL(url).pathname.split("/").pop();
  return PAGES.includes(name) ? name : "index.html";
}

function pageFromNetwork(request, page) {
  return new Promise((resolve, reject) => {
    const timer = setTimeout(() => reject(new Error("slow network")), NETWORK_TIMEOUT_MS);
    // no-cache: revalidate with the server (a cheap 304), not GitHub Pages' 10-minute HTTP cache.
    fetch(request.url, { cache: "no-cache", credentials: "same-origin" }).then((response) => {
      clearTimeout(timer);
      if (response.ok) {
        const copy = response.clone();
        caches.open(CACHE).then((cache) => cache.put(page, copy));
      }
      resolve(response);
    }, (error) => { clearTimeout(timer); reject(error); });
  });
}

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;
  const url = new URL(request.url);

  if (request.mode === "navigate") {
    const page = pageOf(request.url);
    event.respondWith(pageFromNetwork(request, page).catch(() =>
      caches.match(page, { ignoreSearch: true }).then((hit) => hit || fetch(request))));
    return;
  }

  const same = url.origin === self.location.origin;
  // The app's local servers probed by the status lights: never cache, never intercept.
  if (!same && (url.hostname === "localhost" || url.hostname === "127.0.0.1")) return;

  const ignoreSearch = same && url.pathname.includes("/data/");
  event.respondWith(caches.match(request, { ignoreSearch }).then((hit) => hit || fetch(request).then((response) => {
    if ((response.ok || response.type === "opaque") && !same) {
      const copy = response.clone();
      caches.open(RUNTIME).then((cache) => cache.put(request, copy));
    }
    return response;
  })));
});
`;
writeFileSync(join(OUT, "sw.js"), sw);
console.log(`sw.js: ${PRECACHE.length} files, version ${VERSION}`);
