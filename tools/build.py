"""Assemble index.html from src/ — the page GitHub Pages serves.

Usage:  python tools/build.py          (write index.html)
        python tools/build.py --check  (exit 1 if index.html is out of date)

- src/layout.html is the shell; `<!-- @topics -->` becomes every src/topics/*.html,
  in file-name order (so a new topic is just a new numbered file).
- `<!-- @include path -->` inlines another file, relative to the including file.
- Every local asset URL (assets/...css|js|svg) gets ?v=<content hash>, so a browser
  never runs a cached script against a newer page.
- Every `path:line` mentioned in the guide is checked against assets/data/code-index.js
  (written by tools/build_code.py): a missing file or a line past the end fails the build.
"""

from __future__ import annotations

import hashlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src"
INCLUDE = re.compile(r"^[ \t]*<!-- @include (\S+) -->[ \t]*$", re.M)
ASSET = re.compile(r'((?:src|href)=")(assets/[\w./-]+\.(?:css|js|svg))(")')
CODE_REF = re.compile(r"<code>([\w./-]+\.(?:py|tsx?|sql|ya?ml|template|sh|json|txt|ini))"
                      r"(?::(\d+)(?:[–-](\d+))?)?</code>")
# Mentioned on purpose although they are not in the code snapshot.
NOT_IN_SNAPSHOT = {"client/src/pages/Rules.tsx", "worker.py", "CHANGELOG.md"}


def expand(path: Path, seen: tuple[Path, ...] = ()) -> str:
    if path in seen:
        raise SystemExit(f"include cycle: {' -> '.join(str(p) for p in seen + (path,))}")
    text = path.read_text(encoding="utf-8")

    def inline(m: re.Match) -> str:
        target = (path.parent / m.group(1)).resolve()
        if not target.is_file():
            raise SystemExit(f"{path.relative_to(ROOT)}: @include {m.group(1)} not found")
        return expand(target, seen + (path,)).rstrip("\n")

    return INCLUDE.sub(inline, text)


def version(m: re.Match) -> str:
    file = ROOT / m.group(2)
    if not file.is_file():
        raise SystemExit(f"layout references missing asset {m.group(2)}")
    digest = hashlib.sha256(file.read_bytes()).hexdigest()[:10]
    return f"{m.group(1)}{m.group(2)}?v={digest}{m.group(3)}"


def check_refs(html: str) -> list[str]:
    index_js = (ROOT / "assets" / "data" / "code-index.js").read_text(encoding="utf-8")
    files: dict[str, int] = json.loads(index_js[index_js.index("{"):index_js.rstrip().rstrip(";").rindex("}") + 1])["files"]
    problems = []
    for m in CODE_REF.finditer(html):
        p, a, b = m.group(1), m.group(2), m.group(3)
        if p in NOT_IN_SNAPSHOT:
            continue
        hits = [p] if p in files else [f for f in files if f.endswith("/" + p)]
        if len(hits) > 1:
            hits = [f for f in hits if "/tests/" not in f]
        if len(hits) != 1:
            problems.append(f"{p}: {len(hits)} files match")
        elif a and int(b or a) > files[hits[0]]:
            problems.append(f"{p}:{a}: past the end ({files[hits[0]]} lines)")
    return problems


RECIPE = re.compile(r'<details class="recipe" id="(r\d+)"><summary><span class="tag (\w+)">([^<]+)</span>\s*(\d+)\.\s*(.*?)</summary>', re.S)


def recipe_index(html: str) -> str:
    """A clickable list of every recipe, grouped by difficulty, built from the recipes themselves."""
    groups: dict[str, list[str]] = {}
    labels: dict[str, str] = {}
    for rid, level, label, num, title in RECIPE.findall(html):
        labels[level] = label
        plain = re.sub(r"<[^>]+>", "", title).strip()  # code tags would wrap badly and become links inside a link
        groups.setdefault(level, []).append(
            f'<a href="#{rid}" data-reveal="{rid}"><span class="ri-n">{num}</span> <span dir="auto">{plain}</span></a>')
    cols = "".join(f'<div class="ri-col"><span class="tag {lv}">{labels[lv]}</span>{"".join(groups[lv])}</div>'
                   for lv in ("easy", "med", "hard") if lv in groups)
    total = sum(len(v) for v in groups.values())
    return f'<details class="recipe-index" open><summary>כל {total} המתכונים במבט אחד</summary><div class="ri-grid">{cols}</div></details>'


def build() -> str:
    layout = expand(SRC / "layout.html")
    topics = "\n\n".join(expand(t).rstrip("\n") for t in sorted((SRC / "topics").glob("*.html")))
    html = layout.replace("<!-- @topics -->", topics, 1)
    html = html.replace("<!-- @recipe-index -->", recipe_index(html), 1)
    html = html.replace("<!-- @generated -->",
                        "<!-- Generated by tools/build.py from src/ — edit src/, not this file. -->", 1)
    return ASSET.sub(version, html)


def service_worker(html: str) -> str:
    """src/sw.js with the list of files to keep offline and a version that changes with them."""
    index_js = (ROOT / "assets" / "data" / "code-index.js").read_text(encoding="utf-8")
    commit = re.search(r'"commit":"(\w+)"', index_js).group(1)
    viewer = (ROOT / "assets" / "js" / "code-viewer.js").read_text(encoding="utf-8")
    hljs = re.search(r'HLJS_URL = "([^"]+)"', viewer).group(1)
    assets = sorted(set(re.findall(r'(?:src|href)="(assets/[^"]+\?v=\w+)"', html)))
    precache = ["index.html", "manifest.webmanifest", *assets, f"assets/data/code.js?v={commit}", hljs]
    version = hashlib.sha256((html + "\n".join(precache)).encode("utf-8")).hexdigest()[:12]
    template = (SRC / "sw.js").read_text(encoding="utf-8")
    return template.replace("@VERSION@", version).replace("@PRECACHE@", json.dumps(precache, indent=2))


def main() -> int:
    html = build()
    problems = check_refs(html)
    if problems:
        print("broken code references:\n  " + "\n  ".join(problems))
        return 1
    sw = service_worker(html)
    outputs = {ROOT / "index.html": html, ROOT / "sw.js": sw}
    if "--check" in sys.argv:
        stale = [p.name for p, text in outputs.items() if (p.read_text(encoding="utf-8") if p.exists() else "") != text]
        if stale:
            print(f"{', '.join(stale)} out of date: run python tools/build.py")
            return 1
        print("index.html and sw.js are up to date")
        return 0
    for path, text in outputs.items():
        path.write_text(text, encoding="utf-8", newline="\n")
    topics = len(list((SRC / "topics").glob("*.html")))
    print(f"index.html: {len(html) // 1024} KB from {topics} topics, all code references resolve; sw.js written")
    return 0


if __name__ == "__main__":
    sys.exit(main())
