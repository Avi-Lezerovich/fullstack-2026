"""Snapshot the LolSuit source into assets/data/code.js (contents) and
assets/data/code-index.js (file list + symbols) for the guide's code viewer.

Usage:  python tools/build_code.py <path-to-main-checkout> [--ref HEAD]

Reads committed files only (git show <ref>:<path>), so local edits and .env never
leak into the site. tools/build.py then checks the guide's `path:line`
references against the index this writes.
"""

from __future__ import annotations

import json
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
SKIP_SUFFIX = (".svg", ".png", ".jpg", ".ico", "package-lock.json")
SKIP_NAME = {"CHANGELOG.md", ".gitattributes", ".gitignore", ".dockerignore", ".coveragerc"}

PY_SYMBOLS = [
    (re.compile(r"^\s*(?:async\s+)?def\s+(\w+)"), "def"),
    (re.compile(r"^\s*class\s+(\w+)"), "class"),
    (re.compile(r"^([A-Z][A-Z0-9_]{2,})\s*(?::[^=]+)?="), "const"),
]
TS_SYMBOLS = [
    (re.compile(r"^export\s+(?:default\s+)?(?:async\s+)?(?:function|const|class|interface|type|enum)\s+(\w+)"), "export"),
    (re.compile(r"^(?:const|function|let)\s+(\w+)"), "const"),
    (re.compile(r"^\s{2}(\w+)\s*:\s*\(.*=>"), "fn"),
]
SQL_TABLE = re.compile(r"CREATE TABLE(?: IF NOT EXISTS)?\s+`?(\w+)`?", re.I)
ROUTE = re.compile(r"@bp\.(get|post|put|patch|delete)\(\s*\"([^\"]+)\"")
ENV_NAME = re.compile(r"\"([A-Z][A-Z0-9_]{3,})\"")
COMPOSE_SERVICE = re.compile(r"^  ([a-z][\w-]*):\s*$")


def git(repo: Path, *args: str) -> str:
    return subprocess.run(["git", "-C", str(repo), *args], check=True, capture_output=True,
                          text=True, encoding="utf-8").stdout


def symbols_for(path: str, text: str) -> list[list]:
    out: list[list] = []
    lines = text.split("\n")
    if path.endswith(".py"):
        for n, line in enumerate(lines, 1):
            for rx, kind in PY_SYMBOLS:
                m = rx.match(line)
                if m:
                    out.append([m.group(1), kind, path, n])
                    break
            r = ROUTE.search(line)
            if r:
                out.append([f"{r.group(1).upper()} /api{r.group(2)}", "route", path, n])
            if path.endswith("config.py"):
                for e in ENV_NAME.finditer(line):
                    out.append([e.group(1), "env", path, n])
    elif path.endswith((".ts", ".tsx")) and ".test." not in path:
        for n, line in enumerate(lines, 1):
            for rx, kind in TS_SYMBOLS:
                m = rx.match(line)
                if m:
                    out.append([m.group(1), kind, path, n])
                    break
    elif path.endswith(".sql"):
        for n, line in enumerate(lines, 1):
            m = SQL_TABLE.search(line)
            if m:
                out.append([m.group(1), "table", path, n])
    elif path == "docker-compose.yml":
        in_services = False
        for n, line in enumerate(lines, 1):
            if line.startswith("services:"):
                in_services = True
            elif line and not line.startswith(" ") and not line.startswith("#"):
                in_services = False
            m = COMPOSE_SERVICE.match(line)
            if m and in_services:
                out.append([m.group(1), "service", path, n])
    return out


def main() -> int:
    if len(sys.argv) < 2:
        print(__doc__)
        return 2
    repo = Path(sys.argv[1]).resolve()
    ref = sys.argv[3] if len(sys.argv) > 3 and sys.argv[2] == "--ref" else "HEAD"
    commit = git(repo, "rev-parse", "--short", ref).strip()
    paths = [p for p in git(repo, "ls-tree", "-r", "--name-only", ref).splitlines()
             if not p.endswith(SKIP_SUFFIX) and Path(p).name not in SKIP_NAME]
    files: dict[str, str] = {}
    syms: list[list] = []
    for p in sorted(paths):
        text = git(repo, "show", f"{ref}:{p}").replace("\r\n", "\n")
        files[p] = text
        syms.extend(symbols_for(p, text))
    meta = {"commit": commit, "repo": "https://github.com/Avi-Lezerovich/fullstack-2026",
            "files": {p: t.count("\n") + 1 for p, t in files.items()}, "symbols": syms}
    assets = HERE / "assets" / "data"
    for name, var, data in (("code-index.js", "GUIDE_CODE_INDEX", meta), ("code.js", "GUIDE_CODE", files)):
        (assets / name).write_text("/* generated by tools/build_code.py — do not edit */\nwindow." + var + " = "
                                   + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n",
                                   encoding="utf-8")
        print(f"{name}: {(assets / name).stat().st_size // 1024} KB")
    print(f"{len(files)} files, {len(syms)} symbols, commit {commit}")
    print("now run: python tools/build.py")
    return 0


if __name__ == "__main__":
    sys.exit(main())
