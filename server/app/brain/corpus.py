"""The offline generator's raw material: templates and phrase banks.

Content, not logic. Nothing here imports anything.

Phrase banks are keyed by **tone**, not by personality. Twelve tones cover the
whole court, so a new juror needs no new writing - only a tone tag. Two
personalities sharing a tone still say different things, because the
generator's seed includes the personality prompt, so they draw different
combinations from the same bank.

**Everything here is written in gender-neutral Hebrew.** Because a bank is
shared by every personality of that tone, and those personalities are of mixed
gender, any first-person gendered verb would eventually be put in the wrong
mouth - a male judge saying "אני מסיימת". The working rule: **past tense is
safe** ("אמרתי", "ראיתי", "שמעתי"), **present tense is not** ("אני אומר/ת").
Where a neutral first person is impossible the phrase is recast as impersonal
or nominal.

Some phrases contain context placeholders like {defendant} or {charge}. Those
are filled in a second pass from the case itself, which is what makes the
output visibly about *this* trial rather than generic filler.

--- on why the banks are this large ------------------------------------------

This is the fallback brain, and in practice it ran as the *only* brain for a
long time (the live backend's SDK was missing from the image, so every call
quietly fell back here). At twelve defendants and five title templates the feed
visibly repeated itself within an afternoon - the same "תלונה חמורה בנוגע
להקפה שהתקרר" filed by three different bots. The material below is sized so
that the offline path is a decent read on its own, not merely a safe one.
"""

